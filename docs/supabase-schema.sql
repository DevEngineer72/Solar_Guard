-- Production measurement schema supplied for this application.
create table public.mediciones (
  id bigint generated by default as identity primary key,
  station_id bigint not null,
  uv double precision not null,
  temperatura double precision not null,
  humedad double precision not null,
  created_at timestamptz not null default now()
);

create index mediciones_created_at_idx on public.mediciones (created_at desc);

-- Required for the application's live measurement stream.
alter publication supabase_realtime add table public.mediciones;

-- The mobile/web client uses the public anon/publishable key. If RLS is
-- enabled (recommended), it also needs a SELECT policy or Realtime will not
-- deliver rows to the app. Adjust this policy if the project later adds auth.
alter table public.mediciones enable row level security;
grant select on table public.mediciones to anon, authenticated;
create policy "public can read mediciones"
  on public.mediciones
  for select
  to anon, authenticated
  using (true);
